import sys
sys.set_int_max_str_digits(0)
from l17_orbit2 import canon
NN="(by norm_num)"
def S(st): return "S %d %d %d %d"%st
def gen_step(st):
    """Return (lean_step_term_or_None, eq_lemma_or_None, new_state). Mirrors orbit2.step exactly."""
    a,b,k,s=st
    if a==0 and b>=1:
        q,r=divmod(b,3); new=canon(1+5*q,r,k,s); assert new==(1+5*q,r,k,s)
        return "LEC %d %d %d %d %d %d %s %s %s"%(b,q,r,1+5*q,k,s,NN,NN,NN),None,new
    if b==0 and k>0:
        new=(a+k,s,0,0); return None,"LN %d %d %d %d %s"%(a,k,s,a+k,NN),new
    if b>=3:
        q,r=divmod(b,3); new=(a+5*q,r,k,s)
        return "LCD %d %d %d %d %d %d %d %s %s %s %s"%(a,b,q,r,a+5*q,k,s,NN,NN,NN,NN),None,new
    if b==2:
        if k==0: return "LB2 %d %d %s %s"%(a,2*a+12,NN,NN),None,(0,2*a+12,0,0)
        new=(0,2*a+13,k-1,s); return "LPZ %d %d %d %d %d %s %s %s"%(a,2*a+13,k-1,k,s,NN,NN,NN),None,new
    if b==0: return "LB0 %d %d %s"%(a,2*a+4,NN),None,(0,2*a+4,0,0)
    if k==0: return "LR1 %d %d %d %s %s"%(a,2*a-12,a-7,NN,NN),None,(0,2*a-12,7,3)
    if s==0: return "LF100 %d %d %d %d %s %s"%(a,2*a-12,a-7,k,NN,NN),None,(0,2*a-12,7,2*k+3)
    if s>=3: return "LF111 %d %d %d %d %d %d %s %s %s"%(a,2*a-8,a-5,k,k-1,s-3,NN,NN,NN),None,(0,2*a-8,k+7,s-3)
    raise SystemExit("unsupported state %r"%(st,))
def main(nsteps,per_file,prefix):
    st=(30066981019881,27,0,0)
    from l17_orbit2 import step as ostep
    ref=[st]
    for _ in range(nsteps): ref.append(ostep(ref[-1])[2])
    files=[];cur=[];name0="blank_reaches_boundary3";prev=name0;idx=0;filei=0
    header=lambda i:("import CryptidLink.%s\n/-! Generated by `analysis/leads/l17_gen_orbit.py`: the blank orbit of L17 along one-tail states. -/\n\n"
                     "open BusyBeaver BusyBeaver.SixState Turing\n\nnamespace CryptidLink.L17.Orbit\n\nopen CryptidLink.L17\n\n")%( "L17d" if i==0 else "%s%d"%(prefix,i-1))
    body=[]
    for i in range(nsteps):
        term,eq,new=gen_step(st)
        nm="o%d"%(i+1)
        prevref = prev if prev==name0 else prev
        if term:
            body.append("theorem %s : ReachesPlus target (init []) (%s) :=\n  %s.trans (%s)\n"%(nm,S(new),prevref,term))
        else:
            body.append("theorem %s : ReachesPlus target (init []) (%s) := by\n  rw [← %s]; exact %s\n"%(nm,S(new),eq,prevref))
        prev=nm; st=new
        if st[2]==0 and st[3]>0:
            a,b,k,s_=st; new2=(a,b+s_,0,0); nm2=nm+"m"
            body.append("theorem %s : ReachesPlus target (init []) (%s) := by\n  rw [← LM %d %d %d %d %s]; exact %s\n"%(nm2,S(new2),a,b,s_,b+s_,NN,nm))
            prev=nm2; st=new2
        assert st==ref[i+1], (i,st,ref[i+1])
        if (i+1)%per_file==0 or i+1==nsteps:
            files.append(header(filei)+"".join(body)+"\nend CryptidLink.L17.Orbit\n"); body=[]; filei+=1
    return files,st,prev
if __name__=='__main__':
    n=int(sys.argv[1]); per=int(sys.argv[2]); out=sys.argv[3]; prefix="L17Orbit"
    files,st,last=main(n,per,prefix)
    files[-1]=files[-1].replace("\nend CryptidLink.L17.Orbit\n",
        "\n/-- **L17, machine level.** From the blank tape the machine reaches S(a, 2, 7, 3) with a ≈ 2.04·10^295\n    (981 bits), the endpoint of GPT's 2,000-rewrite derived trace. -/\n"
        "theorem blank_reaches_trace_end : ReachesPlus target (init []) (%s) := %s\n\nend CryptidLink.L17.Orbit\n\n"
        "#print axioms CryptidLink.L17.Orbit.blank_reaches_trace_end\n"%(S(st),last))
    import os
    for i,f in enumerate(files): open(os.path.join(out,"%s%d.lean"%(prefix,i)),"w").write(f)
    print(len(files),"files; last theorem",last,"state bits",[x.bit_length() for x in st])
