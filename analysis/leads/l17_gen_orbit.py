"""Regenerate the five bulk proof dependencies of the tracked L17 endpoint.

The fixed generation recipe and SHA-256 checksums live in link/generated-orbit.json.
Run without arguments before a manual link build, or use scripts/verify.py.
"""
import argparse
import hashlib
import json
from pathlib import Path
from l17_orbit2 import canon
ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "link/generated-orbit.json"
OUTPUT = ROOT / "link/CryptidLink/Generated"
NN="(by norm_num)"
def S(st): return "S %d %d %d %d"%st
def gen_step(st):
    """Return (lean_step_term_or_None, eq_lemma_or_None, new_state). Mirrors orbit2.step exactly."""
    a,b,k,s=st
    if a==0 and b>=1:
        q,r=divmod(b,3); new=canon(1+5*q,r,k,s); assert new==(1+5*q,r,k,s)
        return "LEC %d %d %d %d %d %d %s %s %s"%(b,q,r,1+5*q,k,s,NN,NN,NN),None,new
    if b==0 and k>0:
        new=(a+k,s,0,0); return None,"LN %d %d %d %d %s"%(a,k,s,a+k,NN),new
    if b>=3:
        q,r=divmod(b,3); new=(a+5*q,r,k,s)
        return "LCD %d %d %d %d %d %d %d %s %s %s %s"%(a,b,q,r,a+5*q,k,s,NN,NN,NN,NN),None,new
    if b==2:
        if k==0: return "LB2 %d %d %s %s"%(a,2*a+12,NN,NN),None,(0,2*a+12,0,0)
        new=(0,2*a+13,k-1,s); return "LPZ %d %d %d %d %d %s %s %s"%(a,2*a+13,k-1,k,s,NN,NN,NN),None,new
    if b==0: return "LB0 %d %d %s"%(a,2*a+4,NN),None,(0,2*a+4,0,0)
    if k==0: return "LR1 %d %d %d %s %s"%(a,2*a-12,a-7,NN,NN),None,(0,2*a-12,7,3)
    if s==0: return "LF100 %d %d %d %d %s %s"%(a,2*a-12,a-7,k,NN,NN),None,(0,2*a-12,7,2*k+3)
    if s>=3: return "LF111 %d %d %d %d %d %d %s %s %s"%(a,2*a-8,a-5,k,k-1,s-3,NN,NN,NN),None,(0,2*a-8,k+7,s-3)
    raise SystemExit("unsupported state %r"%(st,))
def main(nsteps,per_file,prefix):
    st=(30066981019881,27,0,0)
    from l17_orbit2 import step as ostep
    ref=[st]
    for _ in range(nsteps): ref.append(ostep(ref[-1])[2])
    files=[];name0="blank_reaches_boundary3";prev=name0;filei=0
    header=lambda i:("import CryptidLink.%s\n/-! Generated by `analysis/leads/l17_gen_orbit.py`: the blank orbit of L17 along one-tail states. -/\n\n"
                     "open BusyBeaver BusyBeaver.SixState Turing\n\nnamespace CryptidLink.L17.Orbit\n\nopen CryptidLink.L17\n\n")%( "L17d" if i==0 else "%s%d"%(prefix,i-1))
    body=[]
    for i in range(nsteps):
        term,eq,new=gen_step(st)
        nm="o%d"%(i+1)
        prevref = prev if prev==name0 else prev
        if term:
            body.append("theorem %s : ReachesPlus target (init []) (%s) :=\n  %s.trans (%s)\n"%(nm,S(new),prevref,term))
        else:
            body.append("theorem %s : ReachesPlus target (init []) (%s) := by\n  rw [← %s]; exact %s\n"%(nm,S(new),eq,prevref))
        prev=nm; st=new
        if st[2]==0 and st[3]>0:
            a,b,k,s_=st; new2=(a,b+s_,0,0); nm2=nm+"m"
            body.append("theorem %s : ReachesPlus target (init []) (%s) := by\n  rw [← LM %d %d %d %d %s]; exact %s\n"%(nm2,S(new2),a,b,s_,b+s_,NN,nm))
            prev=nm2; st=new2
        assert st==ref[i+1], (i,st,ref[i+1])
        if (i+1)%per_file==0 or i+1==nsteps:
            files.append(header(filei)+"".join(body)+"\nend CryptidLink.L17.Orbit\n"); body=[]; filei+=1
    return files,st,prev
def generate(output=OUTPUT, check=False):
    spec = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if spec["schema_version"] != 1:
        raise ValueError("unsupported orbit manifest version")
    files, state, last = main(spec["steps"], spec["steps_per_file"], "Generated.L17Orbit")
    rendered = {f"L17Orbit{i}.lean": source.encode("utf-8") for i, source in enumerate(files)}
    actual = {name: hashlib.sha256(data).hexdigest() for name, data in rendered.items()}
    if actual != spec["sha256"]:
        raise ValueError("generated orbit differs from link/generated-orbit.json; review the recipe and hashes")
    unexpected = {p.name for p in output.glob("*.lean")} - rendered.keys()
    if unexpected:
        raise ValueError(f"unexpected generated Lean files: {sorted(unexpected)}")
    if check:
        for name, data in rendered.items():
            path = output / name
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError(f"missing or modified generated source: {path}")
    else:
        output.mkdir(parents=True, exist_ok=True)
        for name, data in rendered.items():
            path = output / name
            if not path.exists() or path.read_bytes() != data:
                path.write_bytes(data)  # UTF-8, LF bytes on every platform.
    print(f"{'checked' if check else 'generated'} {len(files)} files; last theorem {last}; "
          f"state bits {[x.bit_length() for x in state]}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="require existing files to match; do not write")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    try:
        generate(args.output, args.check)
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, f"orbit generation failed: {error}\n")
